/** Même normalisation côté TS : minuscules, sans accents ni ponctuation (sauf « + »). */
export function normChannelName(s: string): string {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9+]+/g, " ")
    .trim();
}

/** Logo embarqué d'une chaîne, ou null (l'appli retombe alors sur l'URL du flux). */
export function getChannelLogo(name: string): ChannelLogo | null {
  const n = normChannelName(name);
  if (BY_NAME[n]) return BY_NAME[n];
  if (/^eurosport 360/.test(n)) return L["eurosport-360-2"];
  if (/^ligue 1\+/.test(n)) return L["ligue-1-plus"];
  if (/^canal\+ (live|sport|foot)/.test(n)) return BY_NAME["canal+"] ?? null;
  return null;
}
